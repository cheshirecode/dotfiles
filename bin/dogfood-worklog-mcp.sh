#!/usr/bin/env bash
# Exercise fresh setup, repeat setup, and real MCP calls with disposable data.
# The source checkout is used as-is; no real vault or client config is changed.
set -euo pipefail
setup_only=0
case "${1:-}" in
  "") ;;
  --setup-only) setup_only=1 ;;
  *) echo "usage: dogfood-worklog-mcp.sh [--setup-only]" >&2; exit 2 ;;
esac
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
scratch="$(mktemp -d "${TMPDIR:-/tmp}/worklog-dogfood.XXXXXX")"
finish() {
  local rc=$?
  if [[ "$rc" -eq 0 ]]; then rm -rf "$scratch";
  else echo "worklog dogfood: failed; retained diagnostics in $scratch" >&2; fi
}
trap finish EXIT
# Reuse package downloads, not user configuration, across disposable HOMEs.
npm_config_cache="$(npm config get cache)"
export npm_config_cache
mkdir -p "$scratch/home"
export HOME="$scratch/home" CODEX_HOME="$scratch/home/.codex" XDG_CONFIG_HOME="$scratch/home/.config"
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
unset WORKLOG_REPO WORKLOG_BIN WORKLOG_LDAP WORKLOG_NS WORKLOG_SESSION_ID BASH_ENV
vault="$HOME/space one/_worklog"
"$ROOT/skills/worklog/bin/bootstrap.sh" apply --repo "$vault" --ns oss --name dogfood --email oss@test
# This file was just generated by bootstrap in this disposable HOME.
# Never approve an existing user's .envrc as part of installation.
direnv allow "$vault"
"$ROOT/bin/install-worklog-mcp.sh" --repo "$vault"
python3 - "$HOME" > "$scratch/before" <<'PY'
import hashlib, pathlib, sys
home = pathlib.Path(sys.argv[1])
for name in ('.codex/config.toml', '.claude.json', '.cursor/mcp.json', '.config/opencode/opencode.json'):
    print(name, hashlib.sha256((home / name).read_bytes()).hexdigest())
PY
"$ROOT/bin/install-worklog-mcp.sh" --repo "$vault"
python3 - "$HOME" > "$scratch/after" <<'PY'
import hashlib, pathlib, sys
home = pathlib.Path(sys.argv[1])
for name in ('.codex/config.toml', '.claude.json', '.cursor/mcp.json', '.config/opencode/opencode.json'):
    print(name, hashlib.sha256((home / name).read_bytes()).hexdigest())
PY
cmp "$scratch/before" "$scratch/after"
node "$ROOT/packages/worklog-memory-mcp/test/configured.js"
# Use the installed runtime for subsequent helper and protocol checks too.
PATH="$(python3 -c 'import json,sys; d=json.load(open(sys.argv[1])); print(next(iter(d["mcpServers"].values()))["env"]["PATH"])' "$HOME/.cursor/mcp.json")"
export PATH
[[ -L "$HOME/.local/bin/worklog-board" ]]
"$HOME/.local/bin/worklog-board" --repo "$vault" --status --json > "$scratch/board-status.json"
python3 - "$scratch/board-status.json" <<'PY'
import json, sys
assert json.load(open(sys.argv[1]))['running'] is False
PY
if [[ "$setup_only" -eq 1 ]]; then
  echo "worklog dogfood: setup and configured startup passed; protocol suite not run (--setup-only)"
  exit 0
fi
(cd "$ROOT/packages/worklog-memory-mcp" && WORKLOG_SOURCE="$vault" npm test)
echo "worklog dogfood: fresh setup, repeat setup, configured MCP startup, and protocol suite passed"
